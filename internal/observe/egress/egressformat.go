package egress

import (
	"fmt"
	"io"
	"strings"

	"github.com/tmatens/container-sec-derive/internal/sidecar"
)

// The v0.8 egress formatters express the outbound allowlist as enforcement
// artifacts — an nftables ruleset and a k8s NetworkPolicy. Unlike the
// compose-security formatters they are a distinct output family: an egress
// allowlist does not map onto cap_drop/devices/read_only. Both lead with the
// inverted-risk caveat (issue #136): the output is a default-deny policy, so a
// destination the workload never exercised is BLOCKED — its incompleteness is a
// runtime-breaking risk, not a recoverable over-grant.

// egressAllowlist returns the observed destinations from the sidecar's egress
// recommendation (nil-safe).
func egressAllowlist(s *sidecar.Sidecar) []sidecar.EgressDest {
	if s == nil || s.EgressRecommendation == nil {
		return nil
	}
	return s.EgressRecommendation.Allowlist
}

// egressCaveatText returns the non-strippable inverted-risk caveat.
func egressCaveatText(s *sidecar.Sidecar) string {
	if s != nil && s.EgressRecommendation != nil && s.EgressRecommendation.Caveat != "" {
		return s.EgressRecommendation.Caveat
	}
	return EgressCaveat
}

// egressResolvers returns the DNS resolver endpoints from the recommendation
// (nil-safe). These are the UDP/53 destinations trace_tcp cannot see; emitting
// them as allow rules is what keeps a default-DROP egress policy from breaking
// name resolution (issue #159).
func egressResolvers(s *sidecar.Sidecar) []sidecar.EgressDest {
	if s == nil || s.EgressRecommendation == nil {
		return nil
	}
	return s.EgressRecommendation.Resolvers
}

// hostnamesFor returns the hostnames recorded for an allowlist destination by
// matching it against the egress_destinations evidence (which carries the
// trace_dns annotation). Used to comment the IP rules with the names that
// resolved to them. Returns nil when DNS was not observed.
func hostnamesFor(s *sidecar.Sidecar, d sidecar.EgressDest) []string {
	if s == nil {
		return nil
	}
	for _, ed := range s.EgressDestinations {
		if ed.Addr == d.Addr && ed.Port == d.Port {
			return ed.Hostnames
		}
	}
	return nil
}

// WriteEgressNftables emits an nftables ruleset: a default-DROP output chain
// that accepts established/related traffic plus one accept rule per observed
// (addr, port). IPv4 destinations use `ip daddr`, IPv6 `ip6 daddr`. An empty
// allowlist emits a pure default-deny chain (deny-all egress) with a prominent
// warning.
func WriteEgressNftables(w io.Writer, s *sidecar.Sidecar) error {
	var b strings.Builder
	fmt.Fprintln(&b, "# Generated by container-sec-derive --observe egress (nftables)")
	fmt.Fprintln(&b, "# WARNING: "+egressCaveatText(s))
	fmt.Fprintln(&b, "table inet csd_egress {")
	fmt.Fprintln(&b, "\tchain output {")
	fmt.Fprintln(&b, "\t\ttype filter hook output priority 0; policy drop;")
	fmt.Fprintln(&b, "\t\tct state established,related accept")
	// DNS resolver rules first (UDP): without these a default-DROP policy blocks
	// name resolution and the workload fails before any TCP connect (#159).
	for _, r := range egressResolvers(s) {
		fam := "ip"
		if r.Version == 6 {
			fam = "ip6"
		}
		fmt.Fprintf(&b, "\t\t%s daddr %s udp dport %d accept # DNS resolver\n", fam, r.Addr, r.Port)
	}
	dests := egressAllowlist(s)
	if len(dests) == 0 {
		fmt.Fprintln(&b, "\t\t# no outbound connections observed — this chain denies ALL egress")
	}
	for _, d := range dests {
		fam := "ip"
		if d.Version == 6 {
			fam = "ip6"
		}
		comment := ""
		if names := hostnamesFor(s, d); len(names) > 0 {
			comment = " # " + strings.Join(names, ", ")
		}
		fmt.Fprintf(&b, "\t\t%s daddr %s tcp dport %d accept%s\n", fam, d.Addr, d.Port, comment)
	}
	fmt.Fprintln(&b, "\t}")
	fmt.Fprintln(&b, "}")
	_, err := io.WriteString(w, b.String())
	return err
}

// WriteEgressNetworkPolicy emits a Kubernetes NetworkPolicy with an Egress rule
// per observed destination (ipBlock /32 for IPv4, /128 for IPv6, TCP port). The
// podSelector is left empty for the operator to scope to the target pod's
// labels — csd observes a container, not a pod's label set.
func WriteEgressNetworkPolicy(w io.Writer, s *sidecar.Sidecar) error {
	var b strings.Builder
	fmt.Fprintln(&b, "# Generated by container-sec-derive --observe egress (k8s NetworkPolicy)")
	fmt.Fprintln(&b, "# WARNING: "+egressCaveatText(s))
	fmt.Fprintln(&b, "apiVersion: networking.k8s.io/v1")
	fmt.Fprintln(&b, "kind: NetworkPolicy")
	fmt.Fprintln(&b, "metadata:")
	fmt.Fprintf(&b, "  name: %s\n", egressPolicyName(s))
	fmt.Fprintln(&b, "spec:")
	fmt.Fprintln(&b, "  # podSelector is intentionally empty — scope this to the target pod's labels.")
	fmt.Fprintln(&b, "  podSelector: {}")
	fmt.Fprintln(&b, "  policyTypes:")
	fmt.Fprintln(&b, "    - Egress")
	dests := egressAllowlist(s)
	resolvers := egressResolvers(s)
	if len(dests) == 0 && len(resolvers) == 0 {
		fmt.Fprintln(&b, "  # no outbound connections observed — an empty egress list denies ALL egress")
		fmt.Fprintln(&b, "  egress: []")
	} else {
		fmt.Fprintln(&b, "  egress:")
		// DNS resolver rules first (UDP): a NetworkPolicy that omits these blocks
		// name resolution and the workload fails (#159).
		for _, r := range resolvers {
			cidr := r.Addr + "/32"
			if r.Version == 6 {
				cidr = r.Addr + "/128"
			}
			fmt.Fprintln(&b, "    # DNS resolver")
			fmt.Fprintln(&b, "    - to:")
			fmt.Fprintln(&b, "        - ipBlock:")
			fmt.Fprintf(&b, "            cidr: %s\n", cidr)
			fmt.Fprintln(&b, "      ports:")
			fmt.Fprintln(&b, "        - protocol: UDP")
			fmt.Fprintf(&b, "          port: %d\n", r.Port)
		}
		for _, d := range dests {
			cidr := d.Addr + "/32"
			if d.Version == 6 {
				cidr = d.Addr + "/128"
			}
			if names := hostnamesFor(s, d); len(names) > 0 {
				fmt.Fprintf(&b, "    # %s\n", strings.Join(names, ", "))
			}
			fmt.Fprintln(&b, "    - to:")
			fmt.Fprintln(&b, "        - ipBlock:")
			fmt.Fprintf(&b, "            cidr: %s\n", cidr)
			fmt.Fprintln(&b, "      ports:")
			fmt.Fprintln(&b, "        - protocol: TCP")
			fmt.Fprintf(&b, "          port: %d\n", d.Port)
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// egressPolicyName derives an RFC1123-ish NetworkPolicy name from the target
// image (preferred) or selector, suffixed - Falls back to "app-egress".
func egressPolicyName(s *sidecar.Sidecar) string {
	base := ""
	if s != nil {
		if s.Image != "" {
			base = s.Image
			// Drop a registry path and a :tag / @digest, keep the final component.
			if i := strings.LastIndexAny(base, "/"); i >= 0 {
				base = base[i+1:]
			}
			if i := strings.IndexAny(base, ":@"); i >= 0 {
				base = base[:i]
			}
		} else {
			base = s.Target.Selector
		}
	}
	base = sanitizeK8sName(base)
	if base == "" {
		base = "app"
	}
	return base + "-egress"
}

// sanitizeK8sName lowercases s and replaces any character outside [a-z0-9-]
// with '-', collapsing leading/trailing dashes — enough for a paste-ready
// metadata.name the operator can refine.
func sanitizeK8sName(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	return strings.Trim(b.String(), "-")
}
